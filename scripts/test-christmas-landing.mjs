const graph = JSON.parse(html.match(/<script type="application\/ld\+json" data-nm-schema="static">([\s\S]*?)<\/script>/)[1])["@graph"];
for (const type of ["CollectionPage", "Service", "BreadcrumbList", "ItemList", "FAQPage"]) assert.equal(graph.filter(node => node["@type"] === type).length, 1);
assert.equal(graph.some(node => ["Product", "Offer", "AggregateOffer"].includes(node["@type"])), false);
const service = graph.find(node => node["@type"] === "Service");

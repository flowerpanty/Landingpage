const clean = text => text.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
const registry = JSON.parse(read("data/site-pages.json"));
const entry = registry.pages.find(page => page.path === "/christmas/");
assert.deepEqual([entry.status, entry.indexing, entry.sitemap, entry.lastmod, entry.breadcrumbName, entry.urlRole], ["active", "index", true, "2026-10-07", "크리스마스 답례품·쿠키 선물", "occasion-landing"]);
assert.ok(read("sitemap.xml").includes(`<loc>${SITE}/christmas/</loc>\n    <lastmod>2026-10-07</lastmod>`));
assert.match(html, /rel="canonical" href="https:\/\/nothingmatters\.co\.kr\/christmas\/"/);
assert.match(html, /name="robots" content="index,follow,max-image-preview:large,max-snippet:-1,max-video-preview:-1"/);
assert.equal((html.match(/<h1\b/g) || []).length, 1);
assert.equal(clean(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)[1]), "크리스마스 답례품과 쿠키 선물");
assert.equal(html.match(/<title>([^<]+)<\/title>/)[1], "크리스마스 답례품·쿠키 선물 | 기업행사·어린이집 단체주문 | 낫띵메터스");
for (const meta of ["description", "naver-site-verification", "og:type", "og:title", "og:description", "og:url", "og:image", "twitter:card", "twitter:title", "twitter:description", "twitter:image"]) assert.ok(html.includes(`="${meta}"`), `missing ${meta}`);
assert.match(html, /<body class="theme-showroom occasion-page christmas-page"/);
for (const file of ["site.css", "showroom.css", "showroom-home.css", "occasion-landing.css", "christmas.css"]) assert.ok(html.includes(`/assets/${file}`));
assert.match(html, /G-DR5XLDB042/);
assert.match(html, /rel="icon"/);
assert.match(html, /data-nm-skip-link/);
assert.match(html, /data-nm-accessibility/);
const sectionOrder = ["hero", "answer-summary", "christmas-products", "gift-occasions", "corporate-christmas", "kids-christmas", "comparison", "order-guide", "order-timeline", "faq", "final-cta"];
assert.deepEqual([...html.matchAll(/<section[^>]*id="([^"]+)"/g)].map(match => match[1]), sectionOrder);
const h2s = [...html.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/g)].map(match => clean(match[1]));
for (const heading of ["크리스마스 쿠키와 디저트", "크리스마스 답례품, 누구에게 선물하면 좋을까요?", "기업 크리스마스 선물과 연말 행사 답례품", "어린이집·유치원 크리스마스 선물", "어떤 크리스마스 디저트를 고르면 좋을까요?", "크리스마스 쿠키 주문 전에 확인하세요", "크리스마스 답례품 주문 전 자주 묻는 질문"]) assert.ok(h2s.includes(heading));
assert.equal([...html.matchAll(/<h2[^>]*>[\s\S]*?<\/h2>\s*<p\b/g)].length, h2s.length, "each H2 should be followed by a direct answer");
const names = ["산타 브루키", "크리스마스 트리 브루키", "크리스마스 얼굴쿠키 4구"];
const slots = ["santa-brookie", "tree-brookie", "christmas-face-cookie"];
const products = [...html.matchAll(/<article class="christmas-product"[^>]*>([\s\S]*?)<\/article>/g)];
assert.deepEqual(products.map(match => clean(match[1].match(/<h3[^>]*>([\s\S]*?)<\/h3>/)[1])), names);
assert.deepEqual([...html.matchAll(/data-image-slot="([^"]+)"/g)].map(match => match[1]), slots);
assert.equal((liveHtml.match(/<img\b/g) || []).length, 0, "missing seasonal images must not produce broken img elements");
for (const filename of ["santa-brookie.jpg", "tree-brookie.jpg", "christmas-face-cookie-4set.jpg"]) assert.ok(html.includes(`/images/christmas/${filename}`));
const visibleBody = clean(liveHtml.match(/<body\b[^>]*>([\s\S]*?)<\/body>/)[1]);
assert.doesNotMatch(visibleBody, /7,800|12개|\d[\d,]*\s*원|\d+\s*월\s*\d+\s*일/);
assert.doesNotMatch(visibleBody, /비행기|공항|탑승|\bFLIGHT\b|\bBOARDING\b|\bGATE\b|무료배송|전국배송/i);
assert.ok(visibleBody.includes("시즌 주문 일정은 주문 오픈 후 안내"));
assert.ok(visibleBody.includes("서울특별시 강서구 송정로 25 1층"));
for (const field of ["제품", "필요 수량", "필요 날짜", "사용 목적", "수령 방법", "포장 요청 사항"]) assert.ok(html.includes(`<dt>${field}</dt>`));
assert.match(html, /<table>/);
assert.match(html, /<caption>/);
assert.equal((html.match(/scope="col"/g) || []).length, 3);
assert.equal((html.match(/scope="row"/g) || []).length, 3);
const css = read("assets/christmas.css");
assert.match(css, /aspect-ratio: 3 \/ 4/);
assert.match(css, /prefers-reduced-motion/);
assert.doesNotMatch(css, /background-image|linear-gradient|radial-gradient|backdrop-filter:\s*blur/);
const quickPicks = html.match(/<nav class="christmas-quick-picks"[\s\S]*?<\/nav>/)?.[0] || "";
assert.deepEqual([...quickPicks.matchAll(/href="#([^"]+)"/g)].map(match => match[1]), slots, "quick choices should lead directly to the three real products");
assert.equal((html.match(/class="christmas-holiday-art christmas-holiday-art--/g) || []).length, 3);
assert.doesNotMatch(css, /@import|@font-face|@keyframes|animation\s*:|transition:\s*all|will-change|url\(/, "holiday decoration must not add asset requests or continuous animation");
assert.ok(Buffer.byteLength(css) < 24 * 1024, "season styles must stay lightweight");
const seasonScripts = [...html.matchAll(/<script[^>]*src="([^"]+)"/g)].map(match => match[1]);
for (const required of ["https://www.googletagmanager.com/gtag/js?id=G-DR5XLDB042", "/assets/site.js"]) assert.ok(seasonScripts.includes(required));

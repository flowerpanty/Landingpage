assert.equal(service.serviceType, "크리스마스 답례품·연말 행사 쿠키 예약 제작");
assert.deepEqual(service.provider, { "@id": `${SITE}/#localbusiness` });
assert.deepEqual(service.areaServed, JSON.parse(read("data/business.json")).areaServed);
assert.deepEqual(graph.find(node => node["@type"] === "ItemList").itemListElement.map(item => [item.name, item.url]), entry.occasionLanding.items.map(item => [item.name, new URL(item.url, SITE).href]));
for (const item of entry.occasionLanding.items) assert.ok(html.includes(`href="${item.url}"`), "ItemList links must be visible");
const visibleFaq = [...html.matchAll(/<details><summary>([^<]+)<\/summary><p>([\s\S]*?)<\/p><\/details>/g)].map(match => [clean(match[1]), clean(match[2])]);
assert.ok(visibleFaq.length >= 8 && visibleFaq.length <= 10);
assert.deepEqual(graph.find(node => node["@type"] === "FAQPage").mainEntity.map(item => [item.name, item.acceptedAnswer.text]), visibleFaq);
assert.ok(visibleFaq.every(([, answer]) => answer.split(/\.\s*/).filter(Boolean).length >= 2), "FAQ answers should give at least two sentences");

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const html = read("bulk/index.html");
const registry = JSON.parse(read("data/site-pages.json"));
const entry = registry.pages.find(page => page.path === "/bulk/");
const clean = text => text.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
const block = id => html.match(new RegExp(`<section[^>]*id="${id}"[^>]*>([\\s\\S]*?)<\\/section>`))[1];
const graph = JSON.parse(html.match(/<script type="application\/ld\+json" data-nm-schema="static">([\s\S]*?)<\/script>/)[1])["@graph"];
assert.match(html.match(/<title>([^<]*)<\/title>/)[1], /쿠키답례품/);
assert.equal((html.match(/<h1\b/g) || []).length, 1);
assert.equal(clean(html.match(/<h1>([\s\S]*?)<\/h1>/)[1]), "쿠키답례품, 용도와 수량에 맞게 고르세요.");
assert.match(html, /rel="canonical" href="https:\/\/nothingmatters.co.kr\/bulk\/"/);
assert.match(html, /name="robots" content="index,follow/);
assert.deepEqual([entry.status, entry.indexing, entry.sitemap, entry.lastmod, entry.breadcrumbName], ["active", "index", true, "2026-10-14", "쿠키답례품"]);
assert.match(read("sitemap.xml"), /<loc>https:\/\/nothingmatters.co.kr\/bulk\/<\/loc>\s*<lastmod>2026-10-14<\/lastmod>/);
assert.deepEqual([...html.matchAll(/<section\b[^>]*id="([^"]+)"/g)].map(match => match[1]), ["mainpage-home", "favor-types", "favor-products", "actual-cases", "cases-quote", "price-guide", "order-checklist", "order-flow", "pickup-info", "faq", "final-cta"]);
const favorCards = [...block("favor-types").matchAll(/<a class="bulk-favor-card"[^>]*href="([^"]+)"/g)];
const farewell = fs.existsSync(path.join(root, "farewell-favor/index.html")) ? "/farewell-favor/" : "/guides/farewell-favor-cookie/";
assert.deepEqual(favorCards.map(match => match[1]), ["/wedding-favor/", "/first-birthday-favor/", "/corporate-gift/", farewell]);
assert.ok(block("favor-types").includes('href="/guides/teacher-snack-gift/"'));
assert.equal(block("favor-types").includes("lucky-cookie"), false);
const productCards = [...block("favor-products").matchAll(/<article class="bulk-product-card">([\s\S]*?)<\/article>/g)].map(match => match[1]);
const productUrls = ["/products/brownie-cookie/", "/products/custom-brownie-cookie/", "/products/handmade-cookie/", "/products/terminal-sand-cookie/"];
assert.equal(productCards.length, 4);
assert.deepEqual(productCards.map(card => card.match(/href="([^"]+)"/)[1]), productUrls);
assert.match(productCards[0], /7,800원[\s\S]*최소 12개/);
assert.match(productCards[1], /7,800원부터[\s\S]*보통 12개 이상 상담/);
assert.match(productCards[2], /4,500원부터[\s\S]*대부분 최소수량 없음/);
assert.match(productCards[3], /6가지 맛[\s\S]*예약·수량 상담/);
assert.doesNotMatch(productCards[3], /\d[\d,]*원|최소\s*\d/);
assert.doesNotMatch(html, /출시 준비 중|disabled|nm-is-hidden|nm-home-lookbook-rail/);
assert.match(block("favor-products"), /bulk-answer/);
assert.match(block("favor-products"), /OTHER GIFTS/);
assert.equal((block("actual-cases").match(/class="bulk-case-card"/g) || []).length, 6);
assert.match(block("actual-cases"), /class="bulk-case-grid"/);
for (const label of ["결혼식", "돌잔치", "기업행사", "퇴사·승진", "학교·기관", "기타 커스텀"]) assert.ok(block("actual-cases").includes(label));
for (const match of html.matchAll(/<img[^>]*src="([^"]+)"/g)) assert.ok(fs.existsSync(path.join(root, match[1])), `missing real image: ${match[1]}`);
assert.match(block("price-guide"), /최종 금액은 제품·수량·문구·포장 옵션/);
for (const type of ["CollectionPage", "BreadcrumbList", "FAQPage", "ItemList"]) assert.equal(graph.filter(node => node["@type"] === type).length, 1);
assert.equal(graph.some(node => ["Product", "Offer", "AggregateOffer"].includes(node["@type"])), false);
assert.deepEqual(graph.find(node => node["@type"] === "ItemList").itemListElement.map(item => new URL(item.url).pathname), productUrls);
const visibleFaq = [...block("faq").matchAll(/<details><summary>([^<]*)<\/summary><p>([\s\S]*?)<\/p><\/details>/g)].map(match => [clean(match[1]), clean(match[2])]);
assert.equal(visibleFaq.length, 7);
assert.deepEqual(graph.find(node => node["@type"] === "FAQPage").mainEntity.map(item => [item.name, item.acceptedAnswer.text]), visibleFaq);
assert.equal((html.match(/class="bulk-floating-nav"/g) || []).length, 1);
assert.equal((html.match(/class="bulk-mobile-sticky"/g) || []).length, 1);
assert.doesNotMatch(html, /class="nm-float-cta"/);
assert.match(html, /data-disable-kakao-float/);
for (const label of ["bulk-hero-quote", "bulk-cases-quote", "bulk-cases-kakao", "bulk-products-quote", "bulk-final-quote", "bulk-final-kakao", "bulk-floating-quote", "bulk-floating-kakao"]) assert.ok(html.includes(`data-analytics-label="${label}"`));
const orderLinks = [...html.matchAll(/<a\b[^>]*data-analytics-event="order_start"[^>]*>/g)];
assert.ok(orderLinks.every(([tag]) => tag.includes('href="/order"')));
const kakaoLinks = [...html.matchAll(/<a\b[^>]*data-analytics-event="consult_click"[^>]*>/g)];
assert.ok(kakaoLinks.every(([tag]) => tag.includes('href="https://pf.kakao.com/_QdCaK/chat"')));
assert.equal((block("mainpage-home").match(/<a\b/g) || []).length, 2);
assert.equal(block("final-cta").includes('href="/magok-cookie/"'), false);
assert.match(read("llms.txt"), /\[쿠키답례품 대표 허브\]\(https:\/\/nothingmatters.co.kr\/bulk\/\)/);
assert.match(read("index.html"), /쿠키답례품 전체 보기 →/);
for (const match of html.matchAll(/href="(\/[^"#]*)"/g)) {
  const route = new URL(match[1], "https://nothingmatters.co.kr").pathname;
  assert.ok(route === "/" || fs.existsSync(path.join(root, route)) || fs.existsSync(path.join(root, `${route}.html`)), `missing linked route: ${route}`);
}

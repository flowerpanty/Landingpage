import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { playwrightRuntime } from './notice-browser-support.mjs';

const { chromium } = playwrightRuntime();
const base = process.env.WISHING_TREE_TEST_URL || 'http://127.0.0.1:4177/wishing-tree/';
const output = path.resolve('output/playwright/wishing-tree');
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const errors = [], network = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => network.push(request.url()));
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#tree-stage').dataset.renderer === 'webgl', { timeout: 60000 });
  await page.evaluate(async()=>{await document.fonts.load('500 16px SeoulAlrim','크리스마스');await document.fonts.load('700 20px SeoulAlrim','마음');await document.fonts.ready;});
  assert.ok(await page.evaluate(()=>[...document.fonts].some(face=>face.family==='SeoulAlrim'&&face.status==='loaded')));
  assert.match(await page.locator('h1').evaluate(el=>getComputedStyle(el).fontFamily),/SeoulAlrim/);
  assert.ok(Number(await page.locator('#tree-stage').getAttribute('data-needles')) > 100000);
  const canvas = page.locator('#tree-canvas canvas');
  assert.equal(await canvas.getAttribute('role'), 'img');
  const startAngle = await page.locator('#tree-stage').getAttribute('data-azimuth');
  const before = await page.screenshot({ path: path.join(output, '3d-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '트리 오른쪽으로 돌리기' }).click();
  await page.waitForFunction(initial => document.querySelector('#tree-stage').dataset.azimuth !== initial, startAngle);
  const rotated = await page.screenshot({ path: path.join(output, '3d-rotated.png'), fullPage: true });
  assert.notDeepEqual(before, rotated, 'rotating changes the rendered geometry');
  await page.getByRole('button', { name: '트리 처음 모습으로 보기' }).click();
  await page.waitForFunction(initial => document.querySelector('#tree-stage').dataset.azimuth === initial, startAngle);
  await canvas.focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(initial => document.querySelector('#tree-stage').dataset.azimuth !== initial, startAngle);
  await page.keyboard.press('0');
  await page.waitForFunction(initial => document.querySelector('#tree-stage').dataset.azimuth === initial, startAngle);
  const rect = await canvas.boundingBox();
  assert.ok(rect.height > (await page.locator('.intro').boundingBox()).height * 7, 'tree occupies far more space than the short copy');
  await page.mouse.move(rect.x + rect.width * .55, rect.y + rect.height * .4);
  await page.mouse.wheel(0,250);
  await page.waitForFunction(()=>scrollY>100);
  assert.equal(await page.locator('#tree-stage').getAttribute('data-azimuth'),startAngle,'wheel scroll does not rotate the tree');
  await page.mouse.wheel(0,-1000);await page.waitForFunction(()=>scrollY===0);
  await page.mouse.move(rect.x + rect.width * .55, rect.y + rect.height * .4);
  await page.mouse.down();await page.mouse.move(rect.x + rect.width * .7, rect.y + rect.height * .42, { steps: 8 });await page.mouse.up();
  await page.waitForFunction(initial => document.querySelector('#tree-stage').dataset.azimuth !== initial, startAngle);
  await page.getByRole('button', { name: '트리 처음 모습으로 보기' }).click();
  await page.locator('.ornament').first().click();await page.locator('#read-dialog').waitFor({ state: 'visible' });await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.screenshot({ path: path.join(output, '3d-lights.png'), fullPage: true });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  await page.screenshot({ path: path.join(output, '3d-mobile.png'), fullPage: true });
  await context.close();

  const touchContext=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
  const touchPage=await touchContext.newPage();await touchPage.goto(base);
  await touchPage.waitForFunction(()=>document.querySelector('#tree-stage').dataset.renderer==='webgl',{timeout:60000});
  await touchPage.evaluate(()=>document.fonts.ready);
  await touchPage.screenshot({path:path.join(output,'seoul-mobile-viewport.png')});
  const touchAngle=await touchPage.locator('#tree-stage').getAttribute('data-azimuth');
  const cdp=await touchContext.newCDPSession(touchPage);
  const touch=async(type,x,y)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type==='touchEnd'?[]:[{x,y,id:1,radiusX:4,radiusY:4,force:1}]});
  await touch('touchStart',130,500);
  for(let i=1;i<=10;i++)await touch('touchMove',130+i*10,500);
  await touch('touchEnd');await touchPage.waitForFunction(initial=>document.querySelector('#tree-stage').dataset.azimuth!==initial,touchAngle);
  const horizontalResult=await touchPage.evaluate(()=>({y:scrollY,focus:document.activeElement.tagName}));
  assert.ok(horizontalResult.y<10,'horizontal swiping rotates without vertical scrolling: '+JSON.stringify(horizontalResult));
  await touchPage.getByRole('button',{name:'트리 처음 모습으로 보기'}).click();
  await touchPage.waitForFunction(initial=>document.querySelector('#tree-stage').dataset.azimuth===initial,touchAngle);
  await touch('touchStart',90,580);
  for(let i=1;i<=10;i++)await touch('touchMove',90,580-i*22);
  await touch('touchEnd');await touchPage.waitForFunction(()=>scrollY>100);
  assert.equal(await touchPage.locator('#tree-stage').getAttribute('data-azimuth'),touchAngle,'vertical swiping scrolls without rotating');
  await touchPage.getByRole('button',{name:'트리에 편지 달기'}).click();
  assert.equal(await touchPage.locator('html').evaluate(el=>getComputedStyle(el).overflowY),'hidden');
  await touchPage.getByRole('button',{name:'편지 쓰기 닫기'}).click();
  await touchPage.waitForFunction(()=>getComputedStyle(document.documentElement).overflowY==='auto');
  const afterCloseY=await touchPage.evaluate(()=>scrollY);
  await touch('touchStart',90,360);for(let i=1;i<=8;i++)await touch('touchMove',90,360+i*22);await touch('touchEnd');
  await touchPage.waitForFunction(before=>scrollY<before-40,afterCloseY);
  await touchPage.screenshot({path:path.join(output,'seoul-touch-scroll.png'),fullPage:true});
  await touchContext.close();

  const fallbackContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await fallbackContext.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type, ...args) {
      return /^webgl/.test(type) ? null : original.call(this, type, ...args);
    };
  });
  const fallback = await fallbackContext.newPage();
  await fallback.goto(base);
  await fallback.waitForFunction(() => document.querySelector('#tree-stage').dataset.renderer === 'fallback');
  assert.equal(await fallback.locator('#tree-controls').isVisible(), false);
  await fallback.locator('.ornament').first().click();await fallback.locator('#read-dialog').waitFor({ state: 'visible' });await fallback.keyboard.press('Escape');
  await fallback.getByRole('button', { name: '트리에 편지 달기' }).click();await fallback.locator('#compose-dialog').waitFor({ state: 'visible' });
  await fallback.screenshot({ path: path.join(output, '3d-fallback.png') });
  assert.deepEqual(errors, []);
  assert.ok(network.every(url => url.startsWith(new URL(base).origin)), 'renderer uses only locally vendored assets');
  console.log('PASS: Seoul Alrim fonts, tree-first layout, native wheel and vertical touch scrolling, horizontal touch rotation, scrolling after dialog close, WebGL geometry, mouse/keyboard rotation, projected letters, responsive layout, and fallback.');
} finally { await browser.close(); }
